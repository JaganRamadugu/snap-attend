-- ============================================================================
-- ATTENDX AI Database Schema Setup Script
-- ============================================================================
-- This script sets up the PostgreSQL database schema on Supabase.
-- It initializes all necessary tables, constraints, foreign key relationships, 
-- and auto-increment sequences.
-- ============================================================================

-- 1. Create 'teachers' table
CREATE TABLE IF NOT EXISTS public.teachers (
    teacher_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL, -- Hashed with bcrypt
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Create 'students' table
CREATE TABLE IF NOT EXISTS public.students (
    student_id BIGINT PRIMARY KEY, -- Provided manually by student registration
    name VARCHAR(255) NOT NULL,
    face_embedding DOUBLE PRECISION[] NOT NULL, -- Stores the 128-d face embedding vector
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Create 'subjects' table (Classrooms created by Teachers)
CREATE TABLE IF NOT EXISTS public.subjects (
    subject_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    section VARCHAR(50) NOT NULL,
    teacher_id BIGINT REFERENCES public.teachers(teacher_id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Create 'subject_students' table (Join table for Student Enrollment in Subjects)
CREATE TABLE IF NOT EXISTS public.subject_students (
    student_id BIGINT REFERENCES public.students(student_id) ON DELETE CASCADE,
    subject_id BIGINT REFERENCES public.subjects(subject_id) ON DELETE CASCADE,
    enrolled_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    PRIMARY KEY (student_id, subject_id)
);

-- 5. Create 'attendance_logs' table (Attendance logs per subject session)
CREATE TABLE IF NOT EXISTS public.attendance_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES public.students(student_id) ON DELETE CASCADE,
    subject_id BIGINT REFERENCES public.subjects(subject_id) ON DELETE CASCADE,
    is_present BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Create Indexes for Optimized Query Performance
CREATE INDEX IF NOT EXISTS idx_teachers_username ON public.teachers(username);
CREATE INDEX IF NOT EXISTS idx_subjects_teacher_id ON public.subjects(teacher_id);
CREATE INDEX IF NOT EXISTS idx_subject_students_subject_id ON public.subject_students(subject_id);
CREATE INDEX IF NOT EXISTS idx_attendance_logs_subject_id ON public.attendance_logs(subject_id);
CREATE INDEX IF NOT EXISTS idx_attendance_logs_student_id ON public.attendance_logs(student_id);
